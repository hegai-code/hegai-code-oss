#!/usr/bin/env bash
# Свой LLM-шлюз рядом с hub: Bifrost + CLIProxyAPI. Запуск от root из этой папки.
#
#   sudo ./llm.sh enable                 включить шлюз (Bifrost); hub начинает выдавать ключи
#   sudo ./llm.sh add-account NAME       учётка подписки ChatGPT/Codex: свой контейнер
#                                        CLIProxyAPI и пул pool-NAME в Bifrost
#   sudo ./llm.sh login NAME             войти в эту учётку (код с телефона/браузера)
#   sudo ./llm.sh add-provider NAME URL [--responses]
#                                        OpenAI-совместимый API (OpenRouter, DeepSeek,
#                                        vLLM, Ollama...); ключ спросит, не в argv
#   sudo ./llm.sh seat EMAIL...          выдать ключ людям (обычно hub делает сам)
#   sudo ./llm.sh status                 провайдеры, ключи людей, модели
#   sudo ./llm.sh ui                     админка Bifrost на 127.0.0.1:8099, пока открыт (Ctrl-C)
#   sudo ./llm.sh remove-account NAME    убрать учётку (её токены удаляются)
#   sudo ./llm.sh remove-provider NAME
#   sudo ./llm.sh sync                   после правок в админке: шаблон и ключи людей
#                                        ведут во все провайдеры с ключом
#   sudo ./llm.sh disable                выключить шлюз (данные в ./llm остаются)
#
# Как устроено (так же, как работает шлюз у самих разработчиков Hegai Code):
#  - Bifrost: один адрес https://<HEGAI_DOMAIN>/llm/v1 для всех моделей, у каждого
#    человека свой ключ sk-bf-... (hegai:<email>), лимиты, «Расходы» в hub.
#  - Подписка: одна учётка = один контейнер CLIProxyAPI = один пул в Bifrost.
#    Ключи людей ходят во все пулы; модель без префикса Bifrost сам раскладывает
#    по пулам (и при отказе пула может отправить запрос в другой),
#    pool-NAME/<модель> - строго в одну учётку.
#  - Условия подписок у провайдеров - на вас: обычно учётка рассчитана на одного
#    человека, и несколько людей на одной учётке нарушают правила и ведут к бану.
#
# Безопасно перезапускать: каждый шаг пропускает уже сделанное.
set -euo pipefail
cd "$(dirname "$0")"

CPA_IMAGE='eceasy/cli-proxy-api:v7.2.92@sha256:af18f6fb364bfb7b482a1ca6c6c85fd7df2c0d6a3a497ebb82c337ac2216dc41'
LLM_FILES='compose.yml:compose.llm.yml:llm/compose.accounts.yml'
AGENT_USER=hegai
DROPIN_DIR=/etc/systemd/user/cc-remote-agent.service.d
DROPIN="$DROPIN_DIR/hegai-gateway.conf"

die() { echo "$*" >&2; exit 2; }
[ "$(id -u)" = 0 ] || die "Запустите от root: sudo ./llm.sh $*"
[ -r .env ] || die "Нет .env - сначала ./init.sh (или ./install.sh)"
for c in docker python3 openssl; do command -v "$c" >/dev/null || die "Нужен $c"; done

env_get() { grep -E "^$1=" .env | tail -n 1 | cut -d= -f2- | sed -e 's/^["'\'']//' -e 's/["'\'']$//' || true; }
# Replace (or append) KEY=VALUE in .env, keeping it 0600.
env_set() {
  local tmp; tmp="$(mktemp .env.XXXXXX)"; chmod 600 "$tmp"
  grep -v -E "^#?$1=" .env > "$tmp" || true
  printf '%s=%s\n' "$1" "$2" >> "$tmp"
  mv "$tmp" .env
}
env_unset() {
  local tmp; tmp="$(mktemp .env.XXXXXX)"; chmod 600 "$tmp"
  grep -v -E "^$1=" .env > "$tmp" || true
  mv "$tmp" .env
}

DOMAIN="$(env_get HEGAI_DOMAIN)"
[ -n "$DOMAIN" ] || die "В .env не задан HEGAI_DOMAIN"
PUBLIC_URL="https://$DOMAIN/llm/v1"

enabled() { [ -n "$(env_get LLM_GATEWAY_URL)" ] && [ -f llm/bifrost/config.json ]; }
need_enabled() { enabled || die "Шлюз не включён: sudo ./llm.sh enable"; }
dc() { COMPOSE_FILE="$LLM_FILES" docker compose "$@"; }

check_name() {
  [[ "$1" =~ ^[a-z0-9][a-z0-9-]{0,20}$ ]] || die "Имя '$1': латиница в нижнем регистре, цифры, дефис (до 21 символа)"
}

# Admin calls go straight to the Bifrost container from the host; the password
# travels in the environment of that one python process, never in argv.
admin() {
  local cid ip
  cid="$(dc ps -q bifrost)"
  [ -n "$cid" ] || die "Bifrost не запущен: docker compose up -d (или sudo ./llm.sh enable)"
  ip="$(docker inspect -f '{{range $n, $v := .NetworkSettings.Networks}}{{$n}} {{$v.IPAddress}}{{"\n"}}{{end}}' "$cid" | awk '$1 ~ /_llm-admin$/ {print $2; exit}')"
  [ -n "$ip" ] || die "Не нашёл адрес Bifrost в сети llm-admin"
  BF_URL="http://$ip:8080" BF_USER="$(env_get LLM_ADMIN_USER)" BF_PASS="$(env_get LLM_ADMIN_PASSWORD)" \
    TEMPLATE_SEAT="$(env_get CC_REMOTE_LLM_COMMUNITY_TEMPLATE_KEY)" \
    python3 -I llm_admin.py "$@"
}

# llm/compose.accounts.yml: one CLIProxyAPI service per llm/cpa-*/ directory.
write_accounts() {
  local tmp d n
  tmp="$(mktemp llm/compose.accounts.XXXXXX)"
  {
    echo "# Generated by ./llm.sh from llm/cpa-*/ - edit those, not this file."
    echo "services:"
    local any=0
    for d in llm/cpa-*/; do
      [ -f "$d/config.yaml" ] || continue
      n="$(basename "$d")"; n="${n#cpa-}"; any=1
      cat <<YAML
  cpa-$n:
    image: $CPA_IMAGE
    restart: unless-stopped
    networks: [llm]
    volumes:
      - ./llm/cpa-$n/config.yaml:/CLIProxyAPI/config.yaml:ro
      - ./llm/cpa-$n/auth:/root/.cli-proxy-api
    security_opt: [no-new-privileges:true]
    mem_limit: 768m
    pids_limit: 512
    logging:
      driver: json-file
      options: { max-size: "20m", max-file: "5" }
YAML
    done
    [ "$any" = 1 ] || echo "  {}"
  } > "$tmp"
  # `services:` followed by `  {}` is not YAML; fold it.
  if grep -qx '  {}' "$tmp"; then sed -i -e '/^services:$/d' -e 's/^  {}$/services: {}/' "$tmp"; fi
  chmod 600 "$tmp"; mv "$tmp" llm/compose.accounts.yml
}

# The agent of THIS server (connect-host.sh) uses the gateway only when its
# service environment names it. A drop-in in /etc is a convenience, not a
# boundary: the agent's user (and its sessions) can override it with
# ~/.cc-remote/env or its own drop-in - as with every --user agent.
agent_env() {
  id "$AGENT_USER" >/dev/null 2>&1 || return 0
  local uid; uid="$(id -u "$AGENT_USER")"
  if [ "${1:-}" = off ]; then
    [ -e "$DROPIN" ] || return 0
    rm -f "$DROPIN"
  else
    # Explicit modes: callers run under umask 077, and a 0700 directory here
    # is unreadable for the user's systemd - the drop-in would be ignored.
    install -d -m 755 /etc/systemd/user "$DROPIN_DIR"
    printf '[Service]\nEnvironment=CC_REMOTE_GATEWAY_URL=%s\n' "$PUBLIC_URL" > "$DROPIN.new"
    chmod 644 "$DROPIN.new"
    if cmp -s "$DROPIN.new" "$DROPIN" 2>/dev/null; then rm -f "$DROPIN.new"; return 0; fi
    mv "$DROPIN.new" "$DROPIN"
  fi
  if [ -S "/run/user/$uid/bus" ]; then
    runuser -u "$AGENT_USER" -- env "XDG_RUNTIME_DIR=/run/user/$uid" systemctl --user daemon-reload || true
    runuser -u "$AGENT_USER" -- env "XDG_RUNTIME_DIR=/run/user/$uid" systemctl --user try-restart cc-remote-agent.service || true
    if [ "${1:-}" = off ]; then echo "[llm] агент этого сервера: шлюз снят"
    else echo "[llm] агент этого сервера доверяет шлюзу $PUBLIC_URL"; fi
  fi
}

cmd_enable() {
  umask 077
  mkdir -p llm/bifrost
  chmod 700 llm
  if [ -z "$(env_get LLM_ADMIN_PASSWORD)" ]; then
    env_set LLM_ADMIN_USER admin
    env_set LLM_ADMIN_PASSWORD "$(openssl rand -hex 24)"
  fi
  local user pass
  user="$(env_get LLM_ADMIN_USER)"; pass="$(env_get LLM_ADMIN_PASSWORD)"
  [[ "$user$pass" =~ ^[A-Za-z0-9._-]+$ ]] || die "LLM_ADMIN_USER/LLM_ADMIN_PASSWORD: только буквы, цифры, . _ -"
  if [ ! -f llm/bifrost/config.json ]; then
    # Read on Bifrost's FIRST start only; afterwards its database wins.
    # Content logging off: with it on, the full prompt of every turn is kept
    # (a gateway's log database grows by gigabytes a day). Metrics, tokens and
    # the hub's «Расходы» stay. A person's key is required for inference.
    cat > llm/bifrost/config.json <<'JSON'
{
  "client": {
    "enforce_auth_on_inference": true,
    "disable_content_logging": true,
    "log_retention_days": 7,
    "drop_excess_requests": false
  },
  "auth_config": {
    "is_enabled": true,
    "admin_username": "env.BIFROST_ADMIN_USER",
    "admin_password": "env.BIFROST_ADMIN_PASSWORD",
    "disable_auth_on_inference": true
  },
  "config_store": { "enabled": true, "type": "sqlite", "config": { "path": "/app/data/config.db" } },
  "logs_store": { "enabled": true, "type": "sqlite", "config": { "path": "/app/data/logs.db" } },
  "providers": {}
}
JSON
  fi
  chown -R 1000:0 llm/bifrost
  chmod 700 llm/bifrost
  [ -f llm/compose.accounts.yml ] || write_accounts
  env_set COMPOSE_FILE "$LLM_FILES"
  env_set LLM_GATEWAY_URL "http://$user:$pass@bifrost:8080"
  env_set LLM_PUBLIC_URL "$PUBLIC_URL"
  echo "[llm] запускаю Bifrost и перезапускаю hub с шлюзом"
  dc up -d
  # Caddyfile is a bind-mounted file: after an update (git pull replaces the
  # file) the running Caddy still serves the old one, without the /llm/v1
  # routes. A restart re-reads it; agents reconnect on their own.
  dc restart caddy >/dev/null
  admin wait
  agent_env
  cat <<MSG
[llm] шлюз включён: $PUBLIC_URL
Дальше:
  sudo ./llm.sh add-account main      учётка подписки ChatGPT/Codex (повторить для каждой)
  sudo ./llm.sh login main
  sudo ./llm.sh add-provider ...      или/и API-ключи других моделей
MSG
}

cmd_add_account() {
  need_enabled
  local n="${1:-}"; [ -n "$n" ] || die "Использование: ./llm.sh add-account NAME"
  check_name "$n"
  local d="llm/cpa-$n"
  umask 077
  mkdir -p "$d/auth"
  if [ ! -f "$d/config.yaml" ]; then
    local key; key="$(openssl rand -hex 32)"
    cat > "$d/config.yaml" <<YAML
# CLIProxyAPI - one instance per subscription account (./llm.sh add-account).
# The port is never published: only Bifrost reaches it on the llm network.
host: "0.0.0.0"
port: 8317
auth-dir: "/root/.cli-proxy-api"

# The key Bifrost presents (provider pool-$n). Not a person's key.
api-keys:
  - "$key"

# Management API and panel off: empty secret-key = every /v0/management route 404.
remote-management:
  allow-remote: false
  secret-key: ""
  disable-control-panel: true
pprof:
  enable: false
plugins:
  enabled: false

# Blast radius. request-retry also fires on 403, so max-retry-credentials must
# not be 0 ("try all"): a banned login would replay every request onto the next.
request-retry: 2
max-retry-credentials: 1
max-retry-interval: 30
disable-cooling: false
save-cooldown-status: true
transient-error-cooldown-seconds: 0

# fill-first: one login carries the load (and the risk); session affinity keeps
# Codex's prompt cache warm.
routing:
  strategy: "fill-first"
  session-affinity: true
  session-affinity-ttl: "1h"

# No evasion of any kind.
codex:
  identity-confuse: false
disable-claude-cloak-mode: true

debug: false
logging-to-file: true
logs-max-total-size-mb: 512
error-logs-max-files: 10
usage-statistics-enabled: true
ws-auth: true
proxy-url: ""

# Do not inject the host's image_generation tool into /v1/responses: the model
# sends it parameters upstream rejects, and the error cools the login down for
# everyone. An explicit image_generation tool from a client passes as is.
disable-image-generation: "passthrough"
YAML
  fi
  write_accounts
  dc up -d "cpa-$n"
  local key; key="$(sed -n '/^api-keys:/{n;s/^ *- *"\(.*\)"$/\1/p}' "$d/config.yaml")"
  [ -n "$key" ] || die "Не нашёл api-keys в $d/config.yaml"
  PROVIDER_KEY="$key" admin add-pool "$n" "http://cpa-$n:8317" "cpa-$n"
  echo "[llm] учётка $n добавлена (пул pool-$n). Вход: sudo ./llm.sh login $n"
}

cmd_login() {
  need_enabled
  local n="${1:-}"; [ -n "$n" ] || die "Использование: ./llm.sh login NAME"
  check_name "$n"
  [ -f "llm/cpa-$n/config.yaml" ] || die "Нет учётки $n: sudo ./llm.sh add-account $n"
  touch "llm/cpa-$n/.login-started"
  cat <<MSG
[llm] Вход в учётку ChatGPT для $n. Откройте ссылку, введите код и подтвердите
      ОБА шага на странице. Код живёт 15 минут.
MSG
  dc run --rm --no-deps "cpa-$n" ./CLIProxyAPI -codex-device-login || true
  # The login exits 0 even on timeout: the auth file is the only proof.
  if ! find "llm/cpa-$n/auth" -maxdepth 1 -name '*.json' -newer "llm/cpa-$n/.login-started" | grep -q .; then
    rm -f "llm/cpa-$n/.login-started"
    die "Вход не завершён (нового файла в llm/cpa-$n/auth нет). Повторите: sudo ./llm.sh login $n"
  fi
  rm -f "llm/cpa-$n/.login-started"
  dc restart "cpa-$n" >/dev/null
  echo "[llm] вход выполнен; проверяю модели pool-$n"
  local models=""
  for _ in 1 2 3 4 5 6; do
    models="$(admin models "pool-$n" || true)"
    [ -n "$models" ] && break
    sleep 5
  done
  if [ -z "$models" ]; then
    # Bifrost may have cached an empty catalog for a pool that had no login yet.
    echo "[llm] Bifrost не видит моделей pool-$n - перезапускаю его"
    dc restart bifrost >/dev/null
    admin wait
    models="$(admin models "pool-$n" || true)"
  fi
  [ -n "$models" ] || die "Модели pool-$n так и не появились: docker compose logs cpa-$n"
  echo "$models" | sed 's/^/  /'
}

cmd_add_provider() {
  need_enabled
  local n="${1:-}" url="${2:-}" responses=0
  [ -n "$n" ] && [ -n "$url" ] || die "Использование: ./llm.sh add-provider NAME BASE_URL [--responses]
  BASE_URL - адрес OpenAI-совместимого API вместе с /v1, например
    https://openrouter.ai/api/v1   https://api.deepseek.com/v1   http://172.17.0.1:11434/v1 (Ollama на этом сервере)
  --responses - если сервис понимает Responses API (сам OpenAI); иначе только Chat Completions"
  [ "${3:-}" = --responses ] && responses=1
  check_name "$n"
  case "$n" in pool-*) die "Имена pool-* заняты учётками подписок" ;; esac
  case "$url" in http://*|https://*) ;; *) die "BASE_URL должен начинаться с http:// или https://" ;; esac
  local key=""
  if [ -t 0 ]; then
    read -r -s -p "API-ключ для $n (не отображается; для локального сервера без ключа - любое слово): " key; echo
  else
    IFS= read -r key || true
  fi
  [ -n "$key" ] || die "Ключ пустой"
  PROVIDER_KEY="$key" admin add-provider "$n" "$url" "$responses"
  echo "[llm] провайдер $n добавлен. Модели: $n/<модель>; список - sudo ./llm.sh status"
}

cmd_remove_account() {
  need_enabled
  local n="${1:-}"; [ -n "$n" ] || die "Использование: ./llm.sh remove-account NAME"
  check_name "$n"
  admin remove-provider "pool-$n"
  dc rm -sf "cpa-$n" >/dev/null 2>&1 || true
  rm -rf "llm/cpa-$n"
  write_accounts
  dc up -d --remove-orphans >/dev/null
  echo "[llm] учётка $n удалена вместе с её токенами"
}

cmd_ui() {
  need_enabled
  local net
  net="$(docker inspect -f '{{range $n, $v := .NetworkSettings.Networks}}{{$n}}{{"\n"}}{{end}}' "$(dc ps -q bifrost)" | grep '_llm-admin$' | head -n 1)"
  cat <<MSG
[llm] Админка Bifrost: http://127.0.0.1:8099  (логин $(env_get LLM_ADMIN_USER), пароль - LLM_ADMIN_PASSWORD в .env)
      С другого компьютера: ssh -L 8099:127.0.0.1:8099 root@<этот сервер>
      Закрыть - Ctrl-C.
MSG
  local project; project="$(env_get COMPOSE_PROJECT_NAME)"
  docker run --rm --name "${project:-hegai-code}-llm-ui" --network "$net" -p 127.0.0.1:8099:8099 \
    --cap-drop ALL --security-opt no-new-privileges:true \
    alpine/socat@sha256:beb4a68d9e4fe6b0f21ea774a0fde6c31f580dde6368939ed70100c5385b015e tcp-listen:8099,fork,reuseaddr tcp:bifrost:8080
}

cmd_disable() {
  enabled || { echo "[llm] шлюз и так выключен"; return 0; }
  env_unset COMPOSE_FILE
  env_unset LLM_GATEWAY_URL
  env_unset LLM_PUBLIC_URL
  agent_env off
  echo "[llm] выключаю: hub без шлюза, контейнеры Bifrost/CLIProxyAPI останавливаются"
  docker compose up -d --remove-orphans
  echo "[llm] выключено. Данные (ключи людей, входы в учётки) лежат в $(pwd)/llm; включить снова: sudo ./llm.sh enable"
}

cmd="${1:-}"; shift || true
case "$cmd" in
  enable) cmd_enable ;;
  add-account) cmd_add_account "$@" ;;
  login) cmd_login "$@" ;;
  add-provider) cmd_add_provider "$@" ;;
  remove-account) cmd_remove_account "$@" ;;
  remove-provider) need_enabled; check_name "${1:-}"; admin remove-provider "$1" ;;
  sync) need_enabled; admin sync ;;
  seat) need_enabled; [ $# -gt 0 ] || die "Использование: ./llm.sh seat EMAIL..."; admin seat "$@" ;;
  status) need_enabled; admin status ;;
  ui) cmd_ui ;;
  agent-env) enabled && agent_env || true ;;
  disable) cmd_disable ;;
  *) sed -n '2,29p' "$0"; exit 2 ;;
esac
