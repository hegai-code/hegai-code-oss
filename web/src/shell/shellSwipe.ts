/**
 * Пороги и арифметика жеста шторки — зеркало `ios/CCRemote/Shell/ShellSwipe.swift`.
 *
 * **Образец здесь — ПРИЛОЖЕНИЕ, и это исключение из общего правила.** Обычно
 * облик и композицию задаёт веб, а телефон повторяет; жест — то место, где
 * приложение строго лучше, и перенос идёт в обратную сторону. До 22.09 веб
 * решал судьбу жеста целиком в `touchend`: палец возил по стеклу, ничего не
 * двигалось, а потом шторка прилетала анимацией. Именно это владелец нашёл как
 * «шторка открывается не сразу». На телефоне шторка ОТКРЫВАЕТСЯ пальцем, а не
 * открывается ПОСЛЕ пальца.
 *
 * Жест разложен на три вопроса, и каждый — чистая функция:
 *
 *   1. `isHorizontal` — НАШ ли это жест. Спрашивается один раз, на первом
 *      различимом сдвиге (`CLAIM`), и ответ держится до конца тяги.
 *   2. сама тяга — смещение пальца кладётся прямо в геометрию (`useDrawerDrag`).
 *   3. `settle` — куда встать, когда отпустили: расстояние ИЛИ скорость.
 *
 * `isSwipe` осталась и осталась проверяемой: тот же закон, собранный целиком,
 * для всех, кому нужен один ответ вместо трёх.
 *
 * Файл НАМЕРЕННО без импортов: его читают тесты под node, и React сюда не
 * нужен. Числа меняются только вместе с `ShellSwipe.swift` —
 * `ShellSwipeTests.testThresholdsMatchTheWeb` падает, если они разъедутся.
 */

/** Насколько далеко надо утащить, чтобы это считалось жестом. */
export const DIST = 64;
/** Сколько вертикали прощается на ВЕСЬ жест. */
export const SLOP = 44;
/**
 * Во сколько раз горизонталь должна перевесить вертикаль. Диагональный флик
 * во время чтения обязан остаться прокруткой.
 */
export const STRAIGHTNESS = 2;

/**
 * Сдвиг, на котором жест объявляет себя. Не порог срабатывания, а порог
 * РАЗЛИЧИМОСТИ: меньше — и дрожание пальца на тапе поедет карточкой. Прежние
 * 20 тоже годились бы, но их видно: двадцать точек молчания в начале каждого
 * жеста читаются как залипание.
 */
export const CLAIM = 6;

/**
 * Скорость (px/с), на которой флик решает сам, не пройдя расстояния. Короткий
 * бросок от края — самый частый способ открыть шторку одной рукой, и требовать
 * от него полных 64px значит не открывать её вовсе.
 */
export const FLICK = 320;

/** Прошёл ли сдвиг все три условия. */
export function isSwipe(dx: number, dy: number): boolean {
  return Math.abs(dx) >= DIST && Math.abs(dy) <= SLOP && Math.abs(dx) >= Math.abs(dy) * STRAIGHTNESS;
}

/**
 * НАШ ли это жест — решается на первом различимом сдвиге, когда про расстояние
 * ещё ничего не известно.
 *
 * Из трёх условий `isSwipe` здесь применимо ровно одно — прямизна. `DIST` в
 * этот момент заведомо не пройдено (на то он и первый сдвиг), а `SLOP` —
 * абсолютный допуск на ВЕСЬ жест, и мерить им шесть точек значит не мерить
 * ничего: любая дрожь уложится в 44. Прямизна же — отношение, и на шести
 * точках она такая же честная, как на ста.
 */
export function isHorizontal(dx: number, dy: number): boolean {
  return Math.abs(dx) >= Math.abs(dy) * STRAIGHTNESS && Math.abs(dx) > 0;
}

/**
 * Куда встать, когда палец отпущен.
 *
 * Два независимых пути, и оба обязаны быть: медленная тяга решается
 * РАССТОЯНИЕМ (палец довёл шторку до места и отпустил), быстрый бросок —
 * СКОРОСТЬЮ (палец толкнул и убрался). Скорость проверяется ПЕРВОЙ: бросок,
 * не прошедший 64px, — это именно бросок, а не промах. Поэтому же тяга на
 * 200px, швырнутая обратно, шторку не открывает.
 *
 * `wasOpen` меняет не порог, а его сторону: закрывают тем же жестом и тем же
 * расстоянием, которым открывали.
 */
export function settle(dx: number, velocity: number, wasOpen: boolean): boolean {
  if (velocity >= FLICK) return true;
  if (velocity <= -FLICK) return false;
  return wasOpen ? dx > -DIST : dx >= DIST;
}
