/** One screenshot with its caption. `w`/`h` are the file's own pixels: giving
 *  them to the browser reserves the box before the image loads, which is what
 *  stops the text below from jumping while someone is reading it. */
function Shot({ src, alt, caption, w, h, phone, wide, half, eager }: { src: string; alt: string; caption: string; w: number; h: number; phone?: boolean; wide?: boolean; half?: boolean; eager?: boolean }) {
  return (
    <figure className={`install-shot${phone ? ' install-shot--phone' : ''}${wide ? ' install-shot--wide' : ''}${half ? ' install-shot--half' : ''}`}>
      {/* `eager` for the one above the fold: lazy-loading the first picture
          delays the only thing on screen. Everything below stays lazy — this
          page is six screenshots long and most visitors read two screens of it.
          Worth knowing when reviewing a full-page screenshot of this page: the
          lazy ones come back BLANK, because nothing ever scrolled them into
          view. That is the capture, not the page. */}
      {/* Never upscaled past its own pixels. `width: 100%` alone blew the
          430px-wide limits loop up to the full 768px column, which is a blurry
          picture of a crisp UI — and the extra height read as a gap before the
          caption rather than as the image it was. */}
      <img
        src={src} alt={alt} width={w} height={h}
        style={{ maxWidth: `${w}px` }}
        loading={eager ? 'eager' : 'lazy'} decoding="async"
      />
      <figcaption>{caption}</figcaption>
    </figure>
  );
}

