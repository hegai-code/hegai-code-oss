import SwiftUI

// ============================================================================
// Лист, который закрывается тапом СНАРУЖИ.
//
// **Зачем он вообще понадобился.** Системный `.sheet` закрывается только
// перетаскиванием вниз и кнопкой внутри. Палец же тянется туда, где пусто, —
// и «О сессии» на это не отвечал ничем. В вебе того же самого добивается слой
// под панелью с обработчиком клика (`.sheet-scrim`), и он там работает годами.
//
// **Почему не «просто включить системное поведение».** Его нет: у
// `UISheetPresentationController` затемняющий слой касания не обрабатывает, а
// лезть к нему в обход SwiftUI — значит держать хук на приватную иерархию
// презентации. Слой же просто лежит, как в вебе.
//
// **Как это сделано.** Лист поднимается во всю высоту с ПРОЗРАЧНЫМ фоном
// (`presentationBackground(.clear)`), а панель занимает внутри него нижнюю
// долю. Всё, что выше панели, — это не «вне листа», это его собственная
// пустая часть, и повесить на неё обработчик можно. Системное затемнение при
// этом на месте: оно рисуется ПОЗАДИ листа и к его фону отношения не имеет.
//
// Побочно чинится и то, за чем никто не шёл: системная тяга вниз теперь
// работает по всей высоте, включая пустую часть, а не только по панели.
//
// **Где это НЕЛЬЗЯ применять — и это не оговорка, а граница.** Лист, которым
// принимают РЕШЕНИЕ, меняющее состояние, обязан остаться модальным:
// подтверждение инструмента (`ToolApprovalSheet`) и вопрос агенту
// (`QuestionSheet`). Случайный тап мимо панели там означает «нет» — причём
// «нет», которого человек не говорил, отправленное в работающий прогон.
// Поэтому они по-прежнему поднимаются обычным `.sheet`, и переводить их сюда
// не надо.
// ============================================================================

private struct ProductSheet<SheetContent: View>: ViewModifier {
    @Binding var isPresented: Bool
    /// Какую долю высоты занимает сама панель.
    var height: CGFloat
    @ViewBuilder let sheet: () -> SheetContent

    func body(content: Content) -> some View {
        content.sheet(isPresented: $isPresented) {
            GeometryReader { geo in
                ZStack(alignment: .bottom) {
                    // СЛОЙ. Ровно то, что в вебе лежит под панелью, и он же —
                    // затемнение. Своё, а не системное: системное рисуется
                    // позади ЛИСТА, а лист теперь прозрачный и во весь экран,
                    // поэтому вместе с фоном исчезло и оно (снято кадром
                    // `sheet-light-375`: панель стояла на неприглушённом
                    // экране, и «снаружи» не читалось снаружи).
                    //
                    // `contentShape` обязателен и здесь: без него слой
                    // выглядел бы рабочим, будучи дыркой.
                    Theme.scrim.opacity(0.42)
                        .ignoresSafeArea()
                        .contentShape(Rectangle())
                        .onTapGesture { isPresented = false }

                    panel(sheet)
                        .frame(height: geo.size.height * height)
                }
            }
            // Во всю высоту — иначе «снаружи панели» осталось бы снаружи листа,
            // то есть недосягаемым.
            .presentationDetents([.large])
            .presentationBackground(.clear)
            // Свой указатель на панели вместо системного: системный рисуется
            // по верхнему краю ЛИСТА, а лист теперь прозрачный и во весь экран
            // — указатель висел бы в пустоте посреди затемнения.
            .presentationDragIndicator(.hidden)
        }
    }

    private func panel(_ sheet: () -> SheetContent) -> some View {
        VStack(spacing: 0) {
            Capsule()  // пилюля: указатель перетаскивания
                .fill(Theme.textFaint.opacity(0.55))
                .frame(width: 36, height: 5)
                .padding(.top, 8)
                .padding(.bottom, 4)
                .accessibilityHidden(true)
            sheet()
        }
        .frame(maxWidth: .infinity)
        .background(Theme.bg)
        // Скругление только СВЕРХУ: снизу панель упирается в край экрана, и
        // закруглённый низ оставлял бы под собой две тёмные скобки.
        .clipShape(UnevenRoundedRectangle(topLeadingRadius: Theme.radiusXl,
                                          topTrailingRadius: Theme.radiusXl,
                                          style: .continuous))
        // Панель обязана доставать до низа экрана: `GeometryReader` меряет
        // безопасную область, и без этого под панелью оставалась бы полоса
        // затемнения там, где у телефона живёт индикатор home.
        .ignoresSafeArea(edges: .bottom)
    }
}

extension View {
    /// Лист ПРОДУКТОВЫЙ: показывает факты и закрывается тапом снаружи.
    ///
    /// Для листа, которым принимают решение, это НЕ тот модификатор — см.
    /// разбор наверху файла.
    func productSheet<C: View>(isPresented: Binding<Bool>,
                               height: CGFloat = 0.78,
                               @ViewBuilder content: @escaping () -> C) -> some View {
        modifier(ProductSheet(isPresented: isPresented, height: height, sheet: content))
    }
}
