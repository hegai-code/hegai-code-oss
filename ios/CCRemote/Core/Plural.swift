import Foundation

/// Счётная форма русского существительного.
///
/// Экран Команды показывал «1 сессий» и «1 машин»: число подставлялось в
/// строку, а форма слова была вбита одна — множественная. На живом парке это
/// видно сразу, потому что машина с одной сессией — обычный случай, а не
/// краевой.
///
/// Правило русского счёта смотрит на ДВЕ последние цифры, а не на одну:
/// 1 сессия, 2–4 сессии, 5–20 сессий, 21 сессия, 111 сессий. Вторая строка
/// («сессии») — это не «много», а форма для двух-четырёх, и именно её обычно
/// забывают, потому что в английском таких форм две, а не три.
///
/// Почему не `String.localizedStringWithFormat` со `.stringsdict`: у приложения
/// нет ни одного `.strings` — все строки русские и лежат в коде. Заводить
/// локализационный аппарат ради полудюжины подписей значит заводить второе
/// место, где живёт текст, и первым же расхождением станет подпись, которую
/// забыли туда перенести.
func plural(_ n: Int, _ one: String, _ few: String, _ many: String) -> String {
    let abs = Swift.abs(n)
    let tens = abs % 100
    // 11–14 идут по «many» («одиннадцать сессий»), несмотря на последнюю цифру.
    if (11...14).contains(tens) { return many }
    switch abs % 10 {
    case 1: return one
    case 2...4: return few
    default: return many
    }
}

/// То же вместе с числом: `counted(1, "сессия", "сессии", "сессий")` → «1 сессия».
///
/// Имя НЕ `count`: так зовётся свойство у каждой коллекции Swift, и внутри
/// вьюхи с полем `let count: Int` (а такая есть — бейдж непрочитанного) вызов
/// `count(…)` разрешался бы в это поле и не собирался. Имя общей функции не
/// должно совпадать с самым частым именем свойства в языке.
func counted(_ n: Int, _ one: String, _ few: String, _ many: String) -> String {
    "\(n) \(plural(n, one, few, many))"
}
