// ============================================================================
// Ход транскрипта — и то, чем в нём опознаётся говорящий.
//
// ПЕРЕСБОРКА 22.09.2026. До неё здесь была колонка говорящего: 76pt слева,
// метка, имя, под ними время; реплика человека шла во всю меру, на ступень
// темнее и плотнее ответа. Это добросовестный перенос ДОКУМЕНТНОЙ модели, и
// аргумент под ней настоящий — человек пишет короткую инструкцию, агент
// возвращает структурированный документ, и симметрии между ними нет.
//
// Веб от этой модели отказался 17.09, раньше нас, и его рассуждение записано
// рядом с кодом (`web/src/styles.css`, метки «REDESIGN 2026-09-17»):
//
//   «В этой линзе колонка И ЕСТЬ одна сессия с одним агентом, поэтому СТОРОНА
//   (справа — ты, слева — агент) несёт то, что несла подпись, а дорожка в 76px
//   тратила пятую часть панели на имя, которое никогда не меняется.»
//
// Приложение построили в противоположную сторону — ночная пересборка шла по
// старому канону, — и владелец увидел разницу первым же взглядом. Стратегия с
// 22.09: брать элементы больших готовых приложений, `DESIGN.md` — описание
// текущего состояния, а не запрет менять. Поэтому композиция здесь теперь
// вебовская:
//
//   * подписи говорящего НЕТ ни у кого;
//   * реплика человека — плашка СПРАВА, по ширине содержимого, не шире 86%;
//   * штамп — только у человека, внутри его плашки;
//   * ход агента — во всю меру, без плашки, без имени и БЕЗ ВРЕМЕНИ.
//
// Аргумент старой модели при этом не выброшен и стоит ниже дословно: он всё
// ещё верен ДЛЯ ПОЛНОШИРИННОГО транскрипта, и веб свой такой же комментарий
// сохранил по той же причине.
// ============================================================================

/// Кто говорит в этом ходе и когда. Значение, а не три параметра: именно оно
/// ходит по обоим рендерерам и потому обязано быть одним типом.
///
/// Имя больше не пишется на экране, но никуда не девается: его говорит
/// VoiceOver (см. `TurnRow`). Экран, опознающий говорящего стороной, для
/// незрячего читателя не опознаёт его ничем.
struct TurnSpeaker: Equatable {
    /// Имя, которое БУДЕТ НАЗВАНО. Не роль и не «Вы» — см. `SpeakerName.human`.
    let name: String
    /// Человек или рантайм. Решает СТОРОНУ хода и наличие плашки.
    let isHuman: Bool
    /// Время хода. Показывается, только когда транскрипт его действительно
    /// записал: выдуманное время в моно-строке выглядит ровно как настоящее.
    let ts: Double?
}

/// Имя человека в транскрипте.
///
/// Канон: **«Вы» здесь не называет никого**. Сессию видит и коллега — в общем
/// пространстве второе лицо указывает на читателя, а читателей у одного
/// транскрипта столько же, сколько людей в команде. Поэтому имя берётся из
/// профиля: первое слово полного имени, иначе локальная часть почты.
///
/// Правило пережило редизайн, хотя имя перестало быть видимым: оно звучит в
/// VoiceOver, а там «Вы» ошибается ровно так же.
enum SpeakerName {
    /// Последняя опора, когда хаб ещё не прислал `viewer`: не «Вы» и не пусто.
    static let unknown = "Человек"

    static func human(_ viewer: ViewerContext?) -> String {
        guard let viewer else { return unknown }
        if let full = viewer.fullName {
            let first = full.split(whereSeparator: { $0 == " " || $0 == "\u{00A0}" }).first
            if let first, !first.isEmpty { return String(first) }
        }
        let local = viewer.email?.split(separator: "@").first.map(String.init) ?? ""
        guard !local.isEmpty else { return unknown }
        return local.prefix(1).uppercased() + local.dropFirst()
    }
}

/// Колонка говорящего — НЕ смонтирована с 22.09.2026.
///
/// Оставлена намеренно и по той же причине, по которой веб оставил свои
/// правила `.who` («The gutter rules below are kept, not deleted… restoring the
/// labelled variant is one declaration, not an archaeology exercise»): вернуть
/// подписанный вариант — это передать `speaker` сюда, а не восстанавливать
/// двадцать пять строк по истории. Если она понадобится — она здесь целая.
///
/// Что она делала: метка опознавала (мотив идентичности во всём приложении),
/// имя подтверждало. Порознь они уже не работали — два говорящих одним и тем
/// же шёпотом, один из них без подписи, и длинный транскрипт переставал
/// сообщать, кто говорит.
struct SpeakerGutter: View {
    let speaker: TurnSpeaker

    var body: some View {
        VStack(alignment: .leading, spacing: 5) {
            Avatar(seed: speaker.name, label: speaker.name, size: 24, labelSize: 11)
            Text(speaker.name)
                .font(.ui(Theme.sizeMicro, weight: speaker.isHuman ? .semibold : .regular))
                .foregroundStyle(speaker.isHuman ? Theme.text : Theme.textMuted)
                .lineLimit(1)
                .truncationMode(.tail)
            if let ts = speaker.ts {
                Text(TurnTime.hhmm(ts))
                    .font(.mono(Theme.sizeMicro))
                    .monospacedDigit()
                    .foregroundStyle(Theme.textFaint)
            }
        }
        .frame(width: Theme.speakerGutter, alignment: .leading)
        .accessibilityElement(children: .combine)
        .accessibilityLabel(speaker.ts.map { "\(speaker.name), \(TurnTime.hhmm($0))" } ?? speaker.name)
    }
}

/// Одна строка документа.
///
/// Колонки больше нет, и ход поэтому занимает всю меру: сторону и плашку
/// выбирает само тело (см. `HumanPlate`). Машинная строка (`speaker: nil`) идёт
/// по тому же левому краю, что и проза агента, — у них один говорящий, и
/// отдельного отступа под несуществующую колонку ей больше не нужно.
///
/// Волосяных линий между ходами здесь нет и не появится: двести линий читаются
/// громче, чем двести сказанных вещей. Разделяют ходы воздух и сторона.
struct TurnRow<Content: View>: View {
    var speaker: TurnSpeaker?
    /// Ход продолжает предыдущий того же говорящего — шов плотнее.
    var cont: Bool = false
    @ViewBuilder let content: () -> Content

    var body: some View {
        content()
            .frame(maxWidth: .infinity, alignment: .leading)
            // Воздух вместо колонки. Сверху у нового хода он больше: раньше
            // начало хода отбивала метка в колонке, и отбивать его теперь
            // больше нечем.
            .padding(.top, cont ? Theme.s3 : Theme.s5)
            .padding(.bottom, Theme.s1)
            // Говорящий не написан — значит, он обязан быть СКАЗАН. Контейнер,
            // а не склейка: склейка (`children: .combine`) схлопнула бы
            // раскрывающиеся строки инструментов и ссылки в один кусок текста,
            // то есть купила бы подпись ценой всего, что в ходе нажимается.
            .accessibilityElement(children: .contain)
            .accessibilityLabel(label)
    }

    private var label: String {
        guard let speaker else { return "Действия" }
        guard let ts = speaker.ts else { return speaker.name }
        return "\(speaker.name), \(TurnTime.hhmm(ts))"
    }
}

/// Реплика человека — ПЛАШКА СПРАВА.
///
/// То, что здесь стояло раньше, и почему оно ушло. Реплика шла во всю меру,
/// на вес темнее и на ступень плотнее ответа, «как печатное интервью ставит
/// вопрос против ответа», а плашки не было вовсе — про неё в этом же файле
/// было записано, что пузырь кодирует симметрию, которой здесь нет.
///
/// **Аргумент верен и не отменён — он просто про другой транскрипт.** Он верен
/// для ПОЛНОШИРИННОГО документа с подписанной колонкой. В узкой колонке одной
/// сессии с одним агентом сторона говорит то же самое дешевле: не тратит
/// дорожку, не требует подписи и читается на телефоне без чтения — по форме.
/// Веб держит оба комментария рядом ровно затем же.
///
/// Чего плашка НЕ делает: не берёт цвет действия. `--action` — это кнопки, и
/// утопленная плашка с зелёной линейкой слева (она здесь однажды была) тратила
/// цвет кнопки на абзац прозы. Заливка — `chip`, тот же нейтральный чип, что у
/// тегов; текст внутри возвращается к весу чтения, потому что маркирует теперь
/// плашка, а 500-й вес внутри залитой коробки читается криком.
struct HumanPlate<Content: View>: View {
    /// Время хода, если транскрипт его записал.
    var ts: Double?
    @ViewBuilder let content: () -> Content

    var body: some View {
        HStack(spacing: 0) {
            // Пустое слева — не меньше этого. Так плашка никогда не занимает
            // всю меру (иначе она перестаёт быть плашкой и становится фоном
            // абзаца) и при этом ужимается до содержимого на «ок». В вебе это
            // записано как `max-width: 86%` + `width: fit-content`; на 375pt
            // минимум в 48pt даёт те же 86% и, в отличие от доли, не требует
            // спрашивать ширину у контейнера посреди ленивого списка.
            // Как в ChatGPT: плашка ужимается до текста и стоит у правого
            // края, а слева остаётся не меньше пятой части экрана.
            Spacer(minLength: Theme.s6 * 3)
            VStack(alignment: .trailing, spacing: 2) {
                content()
                    .fixedSize(horizontal: false, vertical: true)
                // Своя строка, а не хвост последней. В вебе штамп вплывает
                // (`float: right`) в конец собственного текста и поэтому не
                // стоит ни строки; во float'а SwiftUI не умеет, а подделывать
                // его резервом из пробелов — значит считать ширину моношрифта
                // руками и разъезжаться на первом же Dynamic Type. Цена
                // честная и названа: у короткой реплики плашка на строку выше.
                // Выиграно при этом главное из того комментария — штамп
                // выровнен по ВНУТРЕННЕМУ краю плашки, а не по краю хода, где
                // он «висел за углом и не совпадал ни с чем».
                if let ts {
                    Text(TurnTime.hhmm(ts))
                        .font(.mono(Theme.sizeMicro, weight: .medium))
                        .monospacedDigit()
                        .foregroundStyle(Theme.textFaint)
                        // Время уже названо в подписи всего хода для VoiceOver
                        // (`TurnRow.label`) — вслух дважды оно не нужно.
                        .accessibilityHidden(true)
                }
            }
            .padding(.horizontal, 14)
            .padding(.vertical, 9)
            .background(Theme.chip,
                        in: RoundedRectangle(cornerRadius: Theme.radiusLg, style: .continuous))
        }
    }
}
