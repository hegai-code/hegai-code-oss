import Foundation

/// Линзы списка сессий — один набор, две оси.
///
/// Их было четыре, а до того шесть. Шесть перечисляла `BoardMode`, делая вид,
/// что это равные места; четыре остались после того, как Live оказался «В
/// работе» по другой оси, а Роадмап и Карта — группировкой по продукту.
///
/// Двух хватило по той же причине, по которой веб оставил две: **Проекты** —
/// это не линза, а своё назначение (в вебе — пункт рельсы «Проекты»), а
/// **Таблица** была Списком, пересказанным столбцами, — та самая «ещё одна
/// вычитка того же списка», которую веб выбросил вместе с Доской.
///
/// Осталось два вопроса, которые действительно разные: что происходило когда
/// (**Список**) и что на какой стадии (**Flow**). String-backed, чтобы
/// `CC_LENS=list|flow` мог назвать линзу для скриншот-прогона; выбор держит
/// роутер.
enum SessionLens: String, CaseIterable, Identifiable {
    case list, flow
    var id: String { rawValue }
    var label: String {
        switch self {
        case .list: return "Список"
        case .flow: return "Flow"
        }
    }
}
