import SwiftUI

/// Пороги жеста шторки — один в один с `web/src/shell/useSwipe.ts`.
///
/// Числа выстраданы там, и повторять их подбор здесь нечем: у нас нет ни того
/// корпуса сессий, ни тех рук. Меняются только вместе с вебом.
///
/// **Жест ИНТЕРАКТИВНЫЙ, и это главное изменение 22.09.** До неё решение
/// принималось целиком в `onEnded`: палец возил по стеклу, ничего не двигалось,
/// а потом шторка прилетала анимацией. Владелец назвал это первым же, что
/// заметил на живом устройстве, — и он прав: на телефоне шторка ОТКРЫВАЕТСЯ
/// пальцем, а не открывается ПОСЛЕ пальца. Референсы (Телеграм, ChatGPT)
/// ведут карточку 1:1 с первого различимого сдвига, поэтому жест здесь теперь
/// разложен на три вопроса, и каждый — своя чистая функция:
///
///   1. `isHorizontal` — НАШ ли это жест. Спрашивается один раз, на первом
///      сдвиге, вместе с `SwipeGuard`; ответ держится до конца тяги.
///   2. сама тяга — `AppShell` кладёт смещение пальца прямо в геометрию.
///   3. `settle` — куда встать, когда отпустили: расстояние ИЛИ скорость.
///
/// `isSwipe` осталась и осталась проверяемой: это тот же закон, только собранный
/// целиком, и он всё ещё описывает «состоявшийся жест» для всех, кому нужен
/// один ответ вместо трёх (зонд приёмки, тесты арифметики).
enum ShellSwipe {
    /// Насколько далеко надо утащить, чтобы это считалось жестом.
    static let distance: CGFloat = 64
    /// Сколько вертикали прощается.
    static let slop: CGFloat = 44
    /// Во сколько раз горизонталь должна перевесить вертикаль. Диагональный
    /// флик во время чтения обязан остаться прокруткой.
    static let straightness: CGFloat = 2

    /// Сдвиг, на котором жест объявляет себя. Не порог срабатывания, а порог
    /// РАЗЛИЧИМОСТИ: меньше — и дрожание пальца на тапе поедет карточкой.
    /// Прежние 20 тоже годились бы, но их видно: двадцать точек молчания в
    /// начале каждого жеста читаются как залипание.
    static let claim: CGFloat = 6

    /// Скорость (pt/с), на которой флик решает сам, не пройдя расстояния.
    /// Короткий бросок от края — самый частый способ открыть шторку одной
    /// рукой, и требовать от него полных 64pt значит не открывать её вовсе.
    static let flick: CGFloat = 320

    /// Прошёл ли сдвиг все три условия. Чистая функция — проверяется тестом.
    static func isSwipe(dx: CGFloat, dy: CGFloat) -> Bool {
        abs(dx) >= distance && abs(dy) <= slop && abs(dx) >= abs(dy) * straightness
    }

    /// НАШ ли это жест — решается на первом различимом сдвиге, когда про
    /// расстояние ещё ничего не известно.
    ///
    /// Из трёх условий `isSwipe` здесь применимо ровно одно — прямизна.
    /// `distance` в этот момент заведомо не пройдено (на то он и первый сдвиг),
    /// а `slop` — абсолютный допуск на ВЕСЬ жест, и мерить им шесть точек
    /// значит не мерить ничего: любая дрожь уложится в 44. Прямизна же —
    /// отношение, и на шести точках она такая же честная, как на ста.
    static func isHorizontal(dx: CGFloat, dy: CGFloat) -> Bool {
        abs(dx) >= abs(dy) * straightness && abs(dx) > 0
    }

    /// Куда встать, когда палец отпущен.
    ///
    /// Два независимых пути, и оба обязаны быть: медленная тяга решается
    /// РАССТОЯНИЕМ (палец довёл шторку до места и отпустил), быстрый бросок —
    /// СКОРОСТЬЮ (палец толкнул и убрался). Скорость проверяется первой:
    /// бросок, не прошедший 64pt, — это именно бросок, а не промах.
    ///
    /// `wasOpen` меняет не порог, а его сторону: закрывают тем же жестом и тем
    /// же расстоянием, которым открывали.
    static func settle(dx: CGFloat, velocity: CGFloat, wasOpen: Bool) -> Bool {
        if velocity >= flick { return true }
        if velocity <= -flick { return false }
        return wasOpen ? dx > -distance : dx >= distance
    }
}

/// Регистр «того, что само прокручивается вбок».
///
/// **Зачем он вообще.** Жест шторки читается ПО НАПРАВЛЕНИЮ, а не от кромки:
/// левую кромку iOS забрал под свой системный «назад», и жест, привязанный к
/// ней, либо не открывается, либо воюет с системой (та же причина, что в
/// `useSwipe.ts`). Но у жеста, который может начаться где угодно, появляется
/// своя беда: транскрипт полон коробок, которые едут вбок сами — код-блоки,
/// ряды чипов, вывод инструментов. Горизонтальная тяга внутри такой коробки —
/// это читатель двигает коробку, а не зовёт шелл. Украсть её значит сделать
/// широкий код нечитаемым ровно на том устройстве, где он и без того читается
/// хуже всего.
///
/// **Почему регистр прямоугольников, а не «кто первый схватил».** В вебе это
/// решается обходом DOM вверх от `e.target`. В SwiftUI родительский жест не
/// знает, по какому ребёнку попали. Вариант «внутренний жест ставит флаг,
/// внешний его читает» существует, но флаг залипает, если внутренний `onEnded`
/// не пришёл, и тогда шторка перестаёт открываться вообще — а это невидимая
/// поломка. Прямоугольник же просто лежит: `onEnded` внешнего жеста проверяет,
/// НАЧАЛСЯ ли сдвиг внутри одной из зарегистрированных коробок, и это ровно тот
/// же вопрос, что задаёт `inSidewaysScroller`, только заданный геометрии.
///
/// **Чего здесь НЕТ по сравнению с вебом** — проверки «коробка шире своей рамы»
/// (`scrollWidth > clientWidth`). В CSS она обязательна: `overflow-y: auto`
/// повышает `overflow-x` до `auto` по спецификации, поэтому под определение
/// попадал сам транскрипт. Здесь совпадений по спецификации не бывает — вбок
/// едет только то, что мы пометили руками, — и различитель не нужен. Цена:
/// ряд чипов, который уместился и никуда не едет, всё равно глушит жест. Это
/// согласованный размен: свайп, начатый на чипе, и так двусмысленный.
@MainActor
@Observable
final class SwipeGuard {
    private var rects: [UUID: CGRect] = [:]

    func register(_ id: UUID, frame: CGRect) { rects[id] = frame }
    func forget(_ id: UUID) { rects[id] = nil }

    /// Глушит ли жест, начатый в этой точке (глобальные координаты).
    func blocks(_ point: CGPoint) -> Bool { Self.blocks(point, in: Array(rects.values)) }

    /// Отдельно, статически и вне актора — чтобы правило проверялось без
    /// SwiftUI и без главного потока.
    nonisolated static func blocks(_ point: CGPoint, in rects: [CGRect]) -> Bool {
        rects.contains { $0.contains(point) }
    }
}

// MARK: - Пометить то, что едет вбок

private struct SidewaysScroller: ViewModifier {
    @Environment(SwipeGuard.self) private var guardian: SwipeGuard?
    /// Стабилен на всё время жизни вида — иначе при каждом перерисовывании в
    /// регистре оставался бы мёртвый прямоугольник.
    @State private var id = UUID()

    func body(content: Content) -> some View {
        content.background(
            GeometryReader { geo in
                // Глобальные координаты: жест шелла читает `startLocation` в той
                // же системе, иначе сравнивать нечего.
                let frame = geo.frame(in: .global)
                Color.clear
                    .onAppear { guardian?.register(id, frame: frame) }
                    .onChange(of: frame) { _, new in guardian?.register(id, frame: new) }
                    .onDisappear { guardian?.forget(id) }
            }
        )
    }
}

extension View {
    /// «Этот вид едет вбок сам» — жест шторки, начатый внутри него, не считается.
    func sidewaysScroller() -> some View { modifier(SidewaysScroller()) }
}

// MARK: - Сам жест

private struct ShellDragGesture: ViewModifier {
    @Environment(SwipeGuard.self) private var guardian: SwipeGuard?
    /// Палец сдвинулся — вот на сколько от начала тяги.
    var onChange: (CGFloat) -> Void
    /// Палец отпущен: пройденное расстояние и скорость на отрыве.
    var onEnd: (CGFloat, CGFloat) -> Void

    /// Что жест решил про себя на первом различимом сдвиге.
    ///
    /// Решается ОДИН раз за тягу и не пересматривается. Иначе жест, начатый
    /// горизонтально и продолженный по дуге, посреди движения переставал быть
    /// нашим — а шторка в этот момент уже уехала за пальцем и замирала на
    /// полпути.
    private enum Claim { case undecided, ours, theirs }
    @State private var claim: Claim = .undecided

    func body(content: Content) -> some View {
        content
            // `simultaneousGesture`, а не `gesture`: сквозь этот же вид должна
            // продолжать работать вертикальная прокрутка транскрипта. Ровно та
            // же причина, по которой в вебе здесь ничего не `preventDefault`ится
            // — и ровно поэтому решение «чей жест» принимается прямизной, а не
            // захватом: захватить у прокрутки нам нечем и не нужно.
            .simultaneousGesture(
                DragGesture(minimumDistance: ShellSwipe.claim, coordinateSpace: .global)
                    .onChanged { value in
                        #if DEBUG
                        DrawerPerformanceProbe.shared.dragChanged(dx: value.translation.width, time: value.time.timeIntervalSince1970)
                        #endif
                        if claim == .undecided { claim = decide(value) ? .ours : .theirs }
                        guard claim == .ours else { return }
                        onChange(value.translation.width)
                    }
                    .onEnded { value in
                        #if DEBUG
                        DrawerPerformanceProbe.shared.dragEnded()
                        #endif
                        // `defer`, а не строка в конце: между `guard` и концом
                        // тела есть ранний выход, и незакрытый `claim` — это
                        // тот самый залипающий флаг, из-за которого шторка
                        // перестаёт открываться НАВСЕГДА и молча.
                        defer { claim = .undecided }
                        guard claim == .ours else { return }
                        onEnd(value.translation.width, value.velocity.width)
                    }
            )
    }

    private func decide(_ value: DragGesture.Value) -> Bool {
        // Коробка, которая едет вбок сама, гасит жест ДО всякой арифметики —
        // это по-прежнему первое, что спрашивается (см. `SwipeGuard`).
        if guardian?.blocks(value.startLocation) == true { return false }
        return ShellSwipe.isHorizontal(dx: value.translation.width,
                                       dy: value.translation.height)
    }
}

extension View {
    /// Горизонтальная тяга шелла — по направлению, не от кромки, и ЗА ПАЛЬЦЕМ.
    ///
    /// Геометрию держит вызывающий (`AppShell`): он один знает ширину шторки,
    /// и он один может отвечать за то, чтобы карточка и шторка ехали на одно и
    /// то же число точек. Раньше сюда приходили два замыкания «открыть» и
    /// «закрыть», и шторка поэтому умела ровно два положения.
    func shellDrag(onChange: @escaping (CGFloat) -> Void,
                   onEnd: @escaping (CGFloat, CGFloat) -> Void) -> some View {
        modifier(ShellDragGesture(onChange: onChange, onEnd: onEnd))
    }
}
